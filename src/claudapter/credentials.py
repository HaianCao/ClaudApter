from __future__ import annotations

import json
import os
import re
import tempfile
from pathlib import Path

from .config import Config, config_path, secret_names
from .errors import ClaudapterError


def env_path(config: Config | None = None) -> Path:
    override = os.environ.get("CLAUDE_CA_ENV_FILE")
    if override:
        return Path(override).expanduser().resolve()
    return (config.path if config and config.path else config_path()).with_name(".env")


def _read(path: Path) -> dict[str, str]:
    if not path.exists():
        return {}
    values = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        name, sep, raw = line.partition("=")
        # Older versions generated digit-leading names for valid numeric IDs.
        # Read those adapter-file entries so existing stores can recover; new
        # saves use the safe namespace generated by secret_names instead.
        valid_name = re.fullmatch(r"[A-Z][A-Z0-9_]*", name) or re.fullmatch(r"[0-9][A-Z0-9_]*_TOKEN", name)
        if not sep or not valid_name:
            raise ClaudapterError("Invalid local .env file.")
        if raw.startswith('"'):
            try:
                value = json.loads(raw)
            except json.JSONDecodeError as exc:
                raise ClaudapterError("Invalid local .env value.") from exc
        else:
            value = raw.strip()
        if not isinstance(value, str):
            raise ClaudapterError("Local .env values must be strings.")
        values[name] = value
    return values


def get_token(config: Config, provider_id: str) -> str:
    name, legacy = secret_names(provider_id)
    values = _read(env_path(config))
    # Legacy keys are accepted only from the explicitly selected adapter dotenv,
    # never from native Claude authentication variables in the environment.
    return values.get(name) or os.environ.get(name, "") or (values.get(legacy, "") if legacy != name else "")


def _write(path: Path, values: dict[str, str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile("w", encoding="utf-8", dir=path.parent, prefix=".secrets-", suffix=".tmp", delete=False) as stream:
            temporary = Path(stream.name)
            stream.write("# ClaudApter secrets. Do not commit or share this file.\n")
            stream.writelines(f"{name}={json.dumps(value)}\n" for name, value in sorted(values.items()))
        os.replace(temporary, path)
    finally:
        if temporary and temporary.exists():
            temporary.unlink()


def store_token(config: Config, provider_id: str, token: str) -> None:
    token = token.strip()
    if not token or "\n" in token or "\r" in token:
        raise ClaudapterError("API key cannot be empty or contain line breaks.")
    path = env_path(config)
    values = _read(path)
    name, legacy = secret_names(provider_id)
    values[name] = token
    if legacy != name:
        values.pop(legacy, None)
    _write(path, values)


def remove_token(config: Config, provider_id: str) -> None:
    path = env_path(config)
    values = _read(path)
    for name in secret_names(provider_id):
        values.pop(name, None)
    if path.exists():
        _write(path, values)
